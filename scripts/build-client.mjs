import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const pkg = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8'));
const output = await build({
  absWorkingDir: root, entryPoints: ['src/client.js'], bundle: true, write: false,
  metafile: true, format: 'cjs', platform: 'browser', target: ['chrome105'],
  external: ['react', '@deepseek-ai/*'],
  loader: { '.css': 'text' }, define: { 'process.env.NODE_ENV': '"production"' },
  legalComments: 'inline',
});
if (Object.keys(output.metafile.inputs).some(path => /node_modules\/react\//u.test(path))) {
  throw new Error('React must be supplied by DSH');
}
const source = '// Generated by npm run build. Edit src/ and lib/ source modules, then rebuild.\n' +
  `window.__ModuleLoader__.load({id:${JSON.stringify(pkg.name)},factory:(require)=>{\nvar module={exports:{}};var exports=module.exports;\n` +
  output.outputFiles[0].text + '\nreturn module.exports;\n}});\n';
const destination = new URL('../lib/client.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== source) throw new Error('lib/client.js is stale; run npm run build');
  console.log('Browser bundle matches its source.');
} else await writeFile(destination, source);
